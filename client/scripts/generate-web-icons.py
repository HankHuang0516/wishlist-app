"""Reproduce Web composition from fixed inputs; candidates never edit inputs."""
from pathlib import Path
from PIL import Image
import hashlib
import json

def compose(client, recipe):
    inputs = client / 'icon-source'
    for key in ('original', 'H'):
        source = inputs / recipe[key]['path']
        assert hashlib.sha256(source.read_bytes()).hexdigest() == recipe[key]['sha256']
    assert recipe['originalTransform'] == 'identity'
    original = Image.open(inputs / recipe['original']['path']).convert('RGBA')
    assert list(original.size) == recipe['canvas']
    placement = recipe['HPlacement']
    assert placement['colorOrOpacityAdjustment'] is False
    layer = Image.open(inputs / recipe['H']['path']).convert('RGBA').resize(tuple(placement['size']), Image.Resampling.LANCZOS)
    assert placement['position'][0] >= 0 and placement['position'][1] >= 0
    assert placement['position'][0] + layer.width <= original.width
    assert placement['position'][1] + layer.height <= original.height
    result = original.copy()
    result.alpha_composite(layer, tuple(placement['position']))
    return original, layer, result

def main():
    client = Path(__file__).resolve().parents[1]
    recipe = json.loads((client / 'icon-source/recipe.json').read_text())
    original, layer, result = compose(client, recipe)
    for name, output in recipe['outputs'].items():
        image = result if output['size'] == original.width else result.resize((output['size'], output['size']), Image.Resampling.LANCZOS)
        target = client / 'public' / name
        image.save(target)
        assert hashlib.sha256(target.read_bytes()).hexdigest() == output['sha256'], f'Unexpected generated bytes: {name}'
    print('All four Web icons reproduce the recorded identity composition.')

if __name__ == '__main__':
    main()
